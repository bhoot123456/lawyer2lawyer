function getMongoUri() {
  if (process.env.NODE_ENV === "production" && process.env.ALLOW_PROD_SEED !== "true") {
    console.error("CRITICAL SAFETY ERROR: Seed script execution blocked in production mode. Set ALLOW_PROD_SEED=true to override.");
    process.exit(1);
  }
  return (
    process.env.MONGO_URI ||
    "mongodb://127.0.0.1:27017/lawyer2lawyer"
  );
}

async function seedDistrictCourtJudges() {
  const DistrictCourtJudge = require("./models/DistrictCourtJudge");

  const ops = districtCourtJudgesData.map((j) => ({
    updateOne: {
      filter: {
        complexId: j.complexId,
        districtId: j.districtId,
        courtRoom: j.courtRoom,
        judgeName: j.judgeName,
      },
      update: {
        $setOnInsert: {
          complexId: j.complexId,
          districtId: j.districtId,
          judgeName: j.judgeName,
          designation: j.designation,
          jurisdiction: j.jurisdiction,
          courtRoom: j.courtRoom,
          vcLink: j.vcLink,
          meetingId: j.meetingId,
          email: j.email || "",
          displayOrder: j.displayOrder,
          status: "published",
          publishedAt: new Date(),
        },
      },
      upsert: true,
    },
  }));

  const chunkSize = 100;
  let insertedCount = 0;

  for (let i = 0; i < ops.length; i += chunkSize) {
    const chunk = ops.slice(i, i + chunkSize);
    const result = await DistrictCourtJudge.bulkWrite(chunk, { ordered: false });
    insertedCount += result.upsertedCount || 0;
  }

  const skippedCount = ops.length - insertedCount;

  return { inserted: insertedCount, skipped: skippedCount, total: districtCourtJudgesData.length };
}

async function main() {
  const mongoUri = getMongoUri();

  console.log("Connecting to MongoDB...");
  await mongoose.connect(mongoUri);
  console.log("MongoDB connected.\n");

  try {
    const result = await seedDistrictCourtJudges();

    console.log("========================================");
    console.log("  DistrictCourtJudge Seed Complete");
    console.log("========================================");
    console.log(`  Total records in dataset : ${result.total}`);
    console.log(`  Inserted (new records)   : ${result.inserted}`);
    console.log(`  Skipped (already exist)  : ${result.skipped}`);
    console.log("========================================\n");
  } finally {
    await mongoose.disconnect();
    console.log("MongoDB disconnected.");
  }
}

main()
  .then(() => process.exit(0))
  .catch((err) => {
    console.error("Seed failed:", err);
    process.exit(1);
  });

